from google import genai
from google.colab import userdata

try:
    # Load Gemini API key
    api_key = userdata.get("GEMINI_API_KEY")

    if not api_key:
        raise ValueError("GEMINI_API_KEY not found")

    client = genai.Client(api_key=api_key)

    print("Environment ready. Comparing prompts...\n")

    # Function to send a prompt
    def send_prompt(prompt):
        response = client.models.generate_content(
            model="gemini-flash-lite-latest",
            contents=prompt
        )
        return response.text

    # Baseline prompt
    baseline_prompt = "Explain recursion."

    # Enhanced prompt
    enhanced_prompt = (
        "You are a computer science professor. "
        "Explain recursion to a beginner using a simple "
        "real-world analogy. Write exactly two paragraphs "
        "using simple English."
    )

    # Generate both responses
    baseline_response = send_prompt(baseline_prompt)
    enhanced_response = send_prompt(enhanced_prompt)

    # Display baseline result
    print("=== BASELINE PROMPT ===")
    print("Prompt:", baseline_prompt)
    print("\nResponse:")
    print(baseline_response)

    # Display enhanced result
    print("\n=== ENHANCED PROMPT ===")
    print("Prompt:", enhanced_prompt)
    print("\nResponse:")
    print(enhanced_response)

    # Compare word counts
    print("\n=== COMPARISON ===")
    print("Baseline word count:",
          len(baseline_response.split()))
    print("Enhanced word count:",
          len(enhanced_response.split()))

    print("\nAnalysis:")
    print("The baseline prompt gives a general explanation.")
    print("The enhanced prompt specifies the role, analogy,")
    print("language level, and output format.")

except ValueError as e:
    print("Error:", e)

except Exception as e:
    print("API/Network Error:", e)